    public function index()
    {
        $books = Book::select(
            'id',
            'author_id',
            'publisher_id',
            'title',
            'slug'
        )
            ->with([
                'author:id,name,publisher_id',
                'publisher:id,publisher_name',
                'genres:id,genre_name',
                'reviews:id,reviewable_id,reviewable_type,user_id,rating,comment',
            ])
            ->get();

        return Inertia::render('books/index', [
            'books' => $books,
        ]);
    }

